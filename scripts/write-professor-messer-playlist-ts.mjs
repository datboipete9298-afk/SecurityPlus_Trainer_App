/**
 * Regenerates src/data/professorMesser701Playlist.ts from the official YouTube playlist (requires yt-dlp).
 * Run: node scripts/write-professor-messer-playlist-ts.mjs
 */
import { execSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const listId = "PLG49S3nxzAnl4QDVqK-hOnoqcSKEIDDuv";
const url = `https://www.youtube.com/playlist?list=${listId}`;

const out = execSync(`yt-dlp --flat-playlist --print "%(playlist_index)s|%(id)s|%(title)s" "${url}"`, {
  encoding: "utf8",
  maxBuffer: 10 * 1024 * 1024,
});

const lines = out
  .trim()
  .split("\n")
  .filter(Boolean);
if (lines.length !== 121) {
  console.error("Expected 121 playlist rows, got", lines.length);
  process.exit(1);
}

const items = lines.map((line) => {
  const pipe = line.indexOf("|");
  const pipe2 = line.indexOf("|", pipe + 1);
  const index = Number(line.slice(0, pipe));
  const videoId = line.slice(pipe + 1, pipe2);
  const title = line.slice(pipe2 + 1);
  const m = title.match(/-\s*(\d+\.\d+)\s*$/);
  const objective = m ? m[1] : null;
  return { index, videoId, title, objective };
});

const body = `/**
 * Official Professor Messer SY0-701 YouTube playlist (121 items).
 * AUTO-GENERATED by scripts/write-professor-messer-playlist-ts.mjs — run yt-dlp to refresh.
 * Playlist: https://www.youtube.com/playlist?list=${listId}
 */
export const PROFESSOR_MESSER_701_PLAYLIST_ID = "${listId}" as const;

export type ProfessorMesserPlaylistItem = {
  index: number;
  videoId: string;
  title: string;
  objective: string | null;
  url: string;
  status: "verified";
};

export const PROFESSOR_MESSER_701_PLAYLIST: readonly ProfessorMesserPlaylistItem[] = ${JSON.stringify(
  items.map((x) => ({
    index: x.index,
    videoId: x.videoId,
    title: x.title,
    objective: x.objective,
    url: `https://www.youtube.com/watch?v=${x.videoId}`,
    status: "verified",
  })),
  null,
  2,
)} as const;

export function messerPlaylistVideoById(videoId: string): ProfessorMesserPlaylistItem | undefined {
  return PROFESSOR_MESSER_701_PLAYLIST.find((v) => v.videoId === videoId);
}

/** Extract X.Y from Messer-style titles when present. */
export function parseObjectiveFromMesserTitle(title: string): string | null {
  const m = title.match(/-\\s*(\\d+\\.\\d+)\\s*$/);
  return m ? m[1] : null;
}
`;

writeFileSync(join(root, "src", "data", "professorMesser701Playlist.ts"), body, "utf8");
console.log("Wrote src/data/professorMesser701Playlist.ts", items.length, "items");
